//! The predefined encodings of simple fonts (ISO 32000-2 §9.6.5 and Annex D.2): StandardEncoding, WinAnsiEncoding and MacRomanEncoding, as the Unicode characters of their codes.
//!
//! The tables were generated from Annex D's character set: WinAnsiEncoding from Windows code page 1252 and MacRomanEncoding from Mac OS Roman, both kept to the characters of PDF's Latin character set and corrected by the notes to Table D.2; StandardEncoding from Table D.2 itself. MacExpertEncoding, whose characters are mostly small capitals and old-style figures with no Unicode equivalent, is refused.

/// A predefined encoding.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum BaseEncoding {
    /// StandardEncoding, Adobe's standard Latin encoding.
    Standard,
    /// WinAnsiEncoding, Windows code page 1252.
    WinAnsi,
    /// MacRomanEncoding, Mac OS Roman.
    MacRoman,
}

impl BaseEncoding {
    /// The encoding named `name`, or `None` for names that are no predefined encoding.
    pub(crate) fn from_name(name: &[u8]) -> Option<Self> {
        match name {
            b"StandardEncoding" => Some(Self::Standard),
            b"WinAnsiEncoding" => Some(Self::WinAnsi),
            b"MacRomanEncoding" => Some(Self::MacRoman),
            _ => None,
        }
    }

    /// The character of `code`, if the encoding has one.
    pub(crate) fn character(self, code: u8) -> Option<char> {
        let table = match self {
            Self::Standard => &STANDARD,
            Self::WinAnsi => &WIN_ANSI,
            Self::MacRoman => &MAC_ROMAN,
        };
        match table[usize::from(code)] {
            0 => None,
            value => char::from_u32(u32::from(value)),
        }
    }
}

