#[cfg(test)]
mod tests {
    use super::BaseEncoding;

    #[test]
    fn maps_codes_as_annex_d_does() {
        assert_eq!(BaseEncoding::WinAnsi.character(b'A'), Some('A'));
        assert_eq!(BaseEncoding::WinAnsi.character(0x27), Some('\''));
        assert_eq!(BaseEncoding::WinAnsi.character(0x80), Some('\u{20AC}'));
        assert_eq!(BaseEncoding::WinAnsi.character(0x92), Some('\u{2019}'));
        assert_eq!(BaseEncoding::WinAnsi.character(0x81), Some('\u{2022}'));
        assert_eq!(BaseEncoding::WinAnsi.character(0xA0), Some(' '));
        assert_eq!(BaseEncoding::WinAnsi.character(0xE9), Some('\u{E9}'));
        assert_eq!(BaseEncoding::WinAnsi.character(0x1F), None);
        assert_eq!(BaseEncoding::Standard.character(0x27), Some('\u{2019}'));
        assert_eq!(BaseEncoding::Standard.character(0x60), Some('\u{2018}'));
        assert_eq!(BaseEncoding::Standard.character(0xAE), Some('\u{FB01}'));
        assert_eq!(BaseEncoding::Standard.character(0xA0), None);
        assert_eq!(BaseEncoding::MacRoman.character(0x8E), Some('\u{E9}'));
        assert_eq!(BaseEncoding::MacRoman.character(0xDB), Some('\u{A4}'));
        assert_eq!(BaseEncoding::MacRoman.character(0xCA), Some(' '));
        assert_eq!(BaseEncoding::MacRoman.character(0xB0), None);
        assert_eq!(BaseEncoding::MacRoman.character(0xF0), None);
        assert_eq!(BaseEncoding::from_name(b"MacExpertEncoding"), None);
    }
}
