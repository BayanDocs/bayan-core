/// The report of `summary` as an HTML page.
#[must_use]
pub fn html(summary: &Summary) -> String {
    let mut page = Page::default();
    page.raw("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\"/>\n<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\"/>\n<title>");
    page.text(&summary.title);
    page.raw("</title>\n<style>\n");
    page.raw(STYLE);
    page.raw("</style>\n</head>\n<body>\n<header>\n<h1>");
    page.text(&summary.title);
    page.raw("</h1>\n<p class=\"lead\">BayanDocs Fidelity Lab: how BayanDocs lays out ");
    page.raw(&summary.overall.documents.to_string());
    page.raw(" documents compared with Microsoft Word (metrics version ");
    page.raw(&summary.metrics.to_string());
    page.raw(").</p>\n</header>\n<main>\n");
    overview(&mut page, summary);
    if let Some(baseline) = &summary.baseline {
        regressions(&mut page, baseline);
    }
    group_table(&mut page, "tiers", "By tier", "Tier", &summary.tiers);
    group_table(
        &mut page,
        "modes",
        "By compatibility mode",
        "Mode",
        &summary.compatibility_modes,
    );
    group_table(
        &mut page,
        "scripts",
        "By script",
        "Script",
        &summary.scripts,
    );
    group_table(
        &mut page,
        "features",
        "By feature",
        "Feature",
        &summary.features,
    );
    correlations(&mut page, summary);
    worst(&mut page, summary);
    refused(&mut page, summary);
    about(&mut page);
    page.raw("</main>\n<footer>Generated by bayan-lab report from the JSON summary of the same run. The page has no scripts and loads nothing from elsewhere.</footer>\n</body>\n</html>\n");
    page.out
}

/// The page being written.
#[derive(Default)]
struct Page {
    out: String,
}

impl Page {
    /// Markup written as it is.
    fn raw(&mut self, markup: &str) {
        self.out.push_str(markup);
    }

    /// Text, escaped; control and invisible formatting characters become U+FFFD, so that a name cannot reorder or hide what follows it.
    fn text(&mut self, text: &str) {
        for character in text.chars() {
            match character {
                '&' => self.out.push_str("&amp;"),
                '<' => self.out.push_str("&lt;"),
                '>' => self.out.push_str("&gt;"),
                '"' => self.out.push_str("&quot;"),
                '\'' => self.out.push_str("&#39;"),
                _ if character.is_control() || invisible(character) => self.out.push('\u{FFFD}'),
                _ => self.out.push(character),
            }
        }
    }

    /// A table cell with a share of breaks, its exact numbers in its title, and a bar.
    fn share_cell(&mut self, totals: Totals) {
        if totals.total == 0 {
            self.raw("<td class=\"muted\">—</td>");
            return;
        }
        let _ = write!(
            self.out,
            "<td title=\"{} of {}\">{}{}</td>",
            totals.agreed,
            totals.total,
            percent(totals.agreed, totals.total),
            bar(totals.agreed, totals.total)
        );
    }

    fn cell(&mut self, value: impl core::fmt::Display) {
        let _ = write!(self.out, "<td>{value}</td>");
    }

    fn tile(&mut self, label: &str, value: &str, detail: &str) {
        self.raw("<div class=\"tile\"><div class=\"label\">");
        self.text(label);
        self.raw("</div><div class=\"value\">");
        self.raw(value);
        self.raw("</div><div class=\"muted\">");
        self.text(detail);
        self.raw("</div></div>\n");
    }

    fn named(&mut self, document: &Named) {
        match &document.name {
            Some(name) => self.text(name),
            None => self.raw("<span class=\"muted\">(private)</span>"),
        }
        let short: String = document.sha256.chars().take(12).collect();
        self.raw(" <code title=\"");
        self.text(&document.sha256);
        self.raw("\">");
        self.text(&short);
        self.raw("</code>");
    }
}

/// Whether a character is an invisible formatting character that could change how the page shows the text around it.
const fn invisible(character: char) -> bool {
    matches!(
        character,
        '\u{061C}'
            | '\u{200B}'..='\u{200F}'
            | '\u{202A}'..='\u{202E}'
            | '\u{2060}'..='\u{2069}'
            | '\u{FEFF}'
            | '\u{FFF9}'..='\u{FFFB}'
    )
}

/// `agreed / total` as a percentage with one decimal, rounded; a share that is not 0 or all never shows as `0.0 %` or `100.0 %`.
fn percent(agreed: u64, total: u64) -> String {
    if total == 0 {
        return "—".to_owned();
    }
    let per_mille = (u128::from(agreed) * 1000 + u128::from(total) / 2) / u128::from(total);
    if agreed > 0 && per_mille == 0 {
        return "&lt;0.1 %".to_owned();
    }
    if agreed < total && per_mille == 1000 {
        return "&gt;99.9 %".to_owned();
    }
    format!("{}.{} %", per_mille / 10, per_mille % 10)
}

/// An inline SVG bar of `agreed / total`, 100 units wide.
fn bar(agreed: u64, total: u64) -> String {
    let per_mille = if total == 0 {
        0
    } else {
        u128::from(agreed) * 1000 / u128::from(total)
    };
    format!(
        "<svg class=\"bar\" width=\"100\" height=\"8\" viewBox=\"0 0 1000 80\" aria-hidden=\"true\"><rect class=\"track\" width=\"1000\" height=\"80\"/><rect class=\"fill\" width=\"{per_mille}\" height=\"80\"/></svg>"
    )
}

/// A spread as `median / p95 / max`, in points.
fn spread(spread: Option<&Spread>) -> String {
    spread.map_or_else(
        || "—".to_owned(),
        |spread| {
            format!(
                "{} / {} / {}",
                points(spread.median),
                points(spread.p95),
                points(spread.max)
            )
        },
    )
}

/// A length in points with three decimals, without the unit.
fn points(length: bayan_lab_layout::layout::Points) -> String {
    let millis = length.millis();
    let sign = if millis < 0 { "-" } else { "" };
    let magnitude = millis.unsigned_abs();
    format!("{sign}{}.{:03}", magnitude / 1000, magnitude % 1000)
}

fn overview(page: &mut Page, summary: &Summary) {
    let all = &summary.overall;
    page.raw("<section id=\"overview\">\n<h2>Overview</h2>\n<div class=\"tiles\">\n");
    page.tile(
        "Compared with Word's layout",
        &format!("{} of {}", all.compared, all.documents),
        &format!(
            "{} without ground truth, {} without BayanDocs' layout, {} failed",
            all.without_reference, all.without_candidate, all.failed
        ),
    );
    page.tile(
        "M1 page counts matching",
        &percent(all.m1.matching, all.m1.documents),
        &format!(
            "{} of {} documents; {} pages apart in all",
            all.m1.matching, all.m1.documents, all.m1.absolute_difference
        ),
    );
    page.tile(
        "M2 page-break agreement",
        &percent(all.m2.agreed, all.m2.total),
        &format!("{} of {} page starts", all.m2.agreed, all.m2.total),
    );
    page.tile(
        "M3 line-break agreement",
        &percent(all.m3.agreed, all.m3.total),
        &format!("{} of {} line starts", all.m3.agreed, all.m3.total),
    );
    page.tile(
        "M4 glyph error x (pt)",
        &spread(all.m4.x.as_ref()),
        &format!(
            "median / 95th percentile / maximum of {} glyphs on {} lines",
            all.m4.glyphs, all.m4.lines
        ),
    );
    page.tile(
        "M4 glyph error y (pt)",
        &spread(all.m4.y.as_ref()),
        "median / 95th percentile / maximum",
    );
    page.tile(
        "M7 hint agreement",
        &percent(all.m7.agreed, all.m7.total),
        &format!(
            "{} of {} hints in {} documents; {} with the hinted page count; {} documents refused",
            all.m7.agreed, all.m7.total, all.m7.documents, all.m7.pages_matching, all.m7.refused
        ),
    );
    page.tile(
        "Text matched",
        &percent(all.text.matched, all.text.reference),
        &format!(
            "{} of {} characters of Word's text; {} alignments cut short",
            all.text.matched, all.text.reference, all.text.incomplete
        ),
    );
    page.raw("</div>\n<ul class=\"muted\">\n");
    for note in &summary.notes {
        page.raw("<li>");
        page.text(note);
        page.raw("</li>\n");
    }
    page.raw("</ul>\n</section>\n");
}

fn regressions(page: &mut Page, baseline: &BaselineComparison) {
    page.raw("<section id=\"regressions\">\n<h2>Against the baseline</h2>\n<p>Compared with <q>");
    page.text(&baseline.title);
    let _ = writeln!(
        page.out,
        "</q>: {} documents in both, {} new, {} gone, {} re-baselined (Word's layout changed, so only M7 was compared).</p>",
        baseline.documents,
        baseline.added,
        baseline.missing.len(),
        baseline.rebaselined.len()
    );
    if baseline.regressions.is_empty() {
        page.raw("<p class=\"gained\">No document lost agreement.</p>\n");
    } else {
        let private = baseline
            .regressions
            .iter()
            .filter(|change| change.document.name.is_none())
            .count();
        let _ = write!(
            page.out,
            "<p class=\"lost\"><strong>{} documents lost agreement</strong>",
            baseline.regressions.len()
        );
        if private > 0 {
            let _ = write!(page.out, ", {private} of them private and not listed");
        }
        page.raw(".</p>\n");
        changes(
            page,
            baseline
                .regressions
                .iter()
                .filter(|change| change.document.name.is_some()),
        );
    }
    if !baseline.improvements.is_empty() {
        let _ = writeln!(
            page.out,
            "<p class=\"gained\">{} documents gained agreement and lost none.</p>",
            baseline.improvements.len()
        );
        changes(
            page,
            baseline
                .improvements
                .iter()
                .filter(|change| change.document.name.is_some()),
        );
    }
    page.raw("</section>\n");
}

fn changes<'c>(page: &mut Page, changes: impl Iterator<Item = &'c crate::summary::Change>) {
    page.raw("<div class=\"scroll\"><table>\n<thead><tr><th>Document</th><th>Page count</th><th>Page breaks lost / gained</th><th>Line breaks lost / gained</th><th>Hints lost / gained</th></tr></thead>\n<tbody>\n");
    for change in changes {
        page.raw("<tr><td>");
        page.named(&change.document);
        page.raw("</td>");
        page.cell(if change.page_count_lost {
            "<span class=\"lost\">lost</span>"
        } else if change.page_count_gained {
            "<span class=\"gained\">gained</span>"
        } else {
            ""
        });
        for delta in [change.page_breaks, change.line_breaks, change.hints] {
            let _ = write!(
                page.out,
                "<td><span class=\"lost\">{}</span> / <span class=\"gained\">{}</span></td>",
                delta.lost, delta.gained
            );
        }
        page.raw("</tr>\n");
    }
    page.raw("</tbody>\n</table></div>\n");
}

fn group_table(
    page: &mut Page,
    id: &str,
    title: &str,
    kind: &str,
    groups: &std::collections::BTreeMap<String, Aggregate>,
) {
    let _ = write!(page.out, "<section id=\"{id}\">\n<h2>{title}</h2>\n");
    if groups.is_empty() {
        page.raw("<p class=\"muted\">No documents.</p>\n</section>\n");
        return;
    }
    let _ = write!(
        page.out,
        "<div class=\"scroll\"><table>\n<thead><tr><th>{kind}</th><th>Documents</th><th>Compared</th><th>M1 pages match</th><th>M2 page breaks</th><th>M3 line breaks</th><th>M4 x (pt)</th><th>M4 y (pt)</th><th>M7 hints</th></tr></thead>\n<tbody>\n"
    );
    for (name, aggregate) in groups {
        page.raw("<tr><td>");
        page.text(name);
        page.raw("</td>");
        page.cell(aggregate.documents);
        page.cell(aggregate.compared);
        page.share_cell(Totals {
            total: aggregate.m1.documents,
            agreed: aggregate.m1.matching,
        });
        page.share_cell(aggregate.m2);
        page.share_cell(aggregate.m3);
        page.cell(spread(aggregate.m4.x.as_ref()));
        page.cell(spread(aggregate.m4.y.as_ref()));
        page.share_cell(Totals {
            total: aggregate.m7.total,
            agreed: aggregate.m7.agreed,
        });
        page.raw("</tr>\n");
    }
    page.raw("</tbody>\n</table></div>\n</section>\n");
}

fn correlations(page: &mut Page, summary: &Summary) {
    page.raw("<section id=\"correlations\">\n<h2>Feature tags most correlated with disagreement</h2>\n<p class=\"muted\">For each feature tag with at least five documents with it and five without, the point-biserial correlation between having the tag and a document's share of breaks that disagree: 1 when only documents with the tag disagree, 0 when the tag makes no difference. The strongest are where work pays most.</p>\n");
    for (title, list) in [
        ("Line breaks (M3)", &summary.correlations.line_breaks),
        ("Hints (M7)", &summary.correlations.hints),
    ] {
        let _ = writeln!(page.out, "<h3>{title}</h3>");
        if list.is_empty() {
            page.raw("<p class=\"muted\">No feature tag goes with more disagreement in this run (too few documents, or all disagree alike).</p>\n");
            continue;
        }
        page.raw("<div class=\"scroll\"><table>\n<thead><tr><th>Feature</th><th>Correlation</th><th>Documents with / without</th><th>Disagreement with / without</th></tr></thead>\n<tbody>\n");
        for correlation in list {
            correlation_row(page, correlation);
        }
        page.raw("</tbody>\n</table></div>\n");
    }
    page.raw("</section>\n");
}

fn correlation_row(page: &mut Page, correlation: &Correlation) {
    page.raw("<tr><td>");
    page.text(&correlation.feature);
    page.raw("</td>");
    let magnitude = correlation.correlation.unsigned_abs();
    let sign = if correlation.correlation < 0 { "-" } else { "" };
    page.cell(format!(
        "{sign}{}.{:03}",
        magnitude / 1000,
        magnitude % 1000
    ));
    page.cell(format!("{} / {}", correlation.with, correlation.without));
    page.cell(format!(
        "{} / {}",
        percent(correlation.disagreement_with, 1000),
        percent(correlation.disagreement_without, 1000)
    ));
    page.raw("</tr>\n");
}

fn worst(page: &mut Page, summary: &Summary) {
    page.raw("<section id=\"worst\">\n<h2>Worst documents</h2>\n<p class=\"muted\">Public documents only, lowest agreement first.</p>\n");
    for (title, list, kind) in [
        (
            "By line-break agreement (M3)",
            &summary.worst.line_breaks,
            "Pages (BayanDocs − Word)",
        ),
        (
            "By hint agreement (M7)",
            &summary.worst.hints,
            "Pages (BayanDocs − hints)",
        ),
    ] {
        let _ = writeln!(page.out, "<h3>{title}</h3>");
        if list.is_empty() {
            page.raw("<p class=\"muted\">No public document has these numbers in this run.</p>\n");
            continue;
        }
        let _ = write!(
            page.out,
            "<div class=\"scroll\"><table>\n<thead><tr><th>Document</th><th>Tier</th><th>Agreement</th><th>{kind}</th></tr></thead>\n<tbody>\n"
        );
        for ranked in list {
            ranked_row(page, ranked);
        }
        page.raw("</tbody>\n</table></div>\n");
    }
    page.raw("</section>\n");
}

fn refused(page: &mut Page, summary: &Summary) {
    page.raw("<section id=\"refused\">\n<h2>Documents that could not be read</h2>\n");
    let entries: Vec<_> = summary
        .documents
        .iter()
        .filter(|entry| entry.problem.is_some() || entry.hints_problem.is_some())
        .collect();
    if entries.is_empty() {
        page.raw("<p class=\"muted\">None.</p>\n</section>\n");
        return;
    }
    let private = entries
        .iter()
        .filter(|entry| entry.document.name.is_none())
        .count();
    let _ = writeln!(
        page.out,
        "<p class=\"muted\">{} documents: a layout that is not valid or a comparison beyond its limits (a failure of the run), or a package that bayan-opc or bayan-xml refuses, which BayanDocs could not open either (M7 then does not apply).{}</p>",
        entries.len(),
        if private > 0 {
            " Private documents are counted, not listed."
        } else {
            ""
        }
    );
    page.raw("<div class=\"scroll\"><table>\n<thead><tr><th>Document</th><th>Comparison</th><th>Hints</th></tr></thead>\n<tbody>\n");
    for entry in entries.iter().filter(|entry| entry.document.name.is_some()) {
        page.raw("<tr><td>");
        page.named(&entry.document);
        page.raw("</td><td class=\"reason\">");
        page.text(entry.problem.as_deref().unwrap_or(""));
        page.raw("</td><td class=\"reason\">");
        page.text(entry.hints_problem.as_deref().unwrap_or(""));
        page.raw("</td></tr>\n");
    }
    page.raw("</tbody>\n</table></div>\n</section>\n");
}

fn ranked_row(page: &mut Page, ranked: &Ranked) {
    page.raw("<tr><td>");
    page.named(&ranked.document);
    page.raw("</td>");
    page.cell(ranked.document.tier.name());
    page.share_cell(ranked.breaks);
    page.cell(format!("{:+}", ranked.page_difference));
    page.raw("</tr>\n");
}

fn about(page: &mut Page) {
    page.raw("<section id=\"about\">\n<h2>How to read this report</h2>\n<p>Each document is laid out twice: by Word, on the lab's reference machine (its PDF, read back by <code>bayan-lab pdf-extract</code>), and by BayanDocs. Both texts are aligned character by character, ignoring spaces and invisible characters, so that a small difference such as a numbering label or a field result does not shift everything after it; then breaks and glyphs are compared through the alignment. Lines that share a baseline, such as the cells of a table row, count as one line on both sides.</p>\n<dl>\n<dt>M1 page count</dt><dd>Documents whose page counts match, and how many pages apart the others are.</dd>\n<dt>M2 page-break agreement</dt><dd>Of Word's pages that have text, the share that start at the same place in the text as a BayanDocs page.</dd>\n<dt>M3 line-break agreement</dt><dd>Of Word's lines that have text, the share that start at the same place in the text as a BayanDocs line.</dd>\n<dt>M4 glyph position error</dt><dd>The median, 95th percentile and maximum distance between the same glyphs on both sides, horizontally (x) and vertically (y), in points, measured only on lines whose breaks agree, on pages whose starts agree.</dd>\n<dt>M5 visual difference</dt><dd>The share of a page's pixels that look different; not measured until the lab can rasterize Word's PDFs.</dd>\n<dt>M6 round-trip integrity</dt><dd>Whether Word opens BayanDocs' saved copy without repair and with the same content: checked on the reference machine, not here.</dd>\n<dt>M7 hint agreement</dt><dd>Of the places where Word recorded, when it last saved the document, that a page began (<code>w:lastRenderedPageBreak</code>), the share where a BayanDocs page begins. Approximate, but free, so it covers every document Word saved.</dd>\n</dl>\n<p>A document without ground truth from Word has only M7. A document whose BayanDocs layout is missing is compared as if BayanDocs had laid it out on no pages: every break disagrees.</p>\n</section>\n");
}
