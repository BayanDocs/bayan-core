//! The fidelity report: a [`Summary`] as one static HTML page (work package LAB-004).
//!
//! The page stands alone: its styles are inline, its charts are inline SVG that this module writes, and it has no scripts, no images, no fonts and no link to anything outside itself, so it renders the same offline, from a CI artifact or a file, and cannot leak that it was opened. It is also well-formed XML after its first line (`<!DOCTYPE html>`), which lets the tests read it strictly. The same summary always gives the same bytes: no clock, integers only, and every list in the summary's order.
//!
//! It shows the overall numbers, regressions against the baseline if the run had one, the tables per tier, compatibility mode, script and feature tag, the feature tags most correlated with disagreement, the worst public documents, and what each metric means. Private (T2) documents appear only inside the numbers.

